export function getMockDiagramById(diagramId) {
  return mockDiagrams.find((diagram) => diagram.id === diagramId);
}

export function getRelatedDiagrams(diagramId, limit = 4) {
  const activeDiagram = getMockDiagramById(diagramId);
  const related = mockDiagrams.filter((diagram) => (
    diagram.id !== diagramId
    && !diagram.trashed
    && (diagram.category === activeDiagram?.category || diagram.published)
  ));

  return related.slice(0, limit);
}
